export type BookingStats = {
  attempts: number | null;
  successes: number | null;
  failures: number | null;
  lastError: string | null;
  lastErrorAt: string | null;
  lastSuccessAt: string | null;
};

/**
 * Why the latest generation attempt failed (or null when it succeeded).
 * Shown verbatim in the booking modal so users learn *why* there's no code
 * instead of a bare "not generated yet".
 */
export async function fetchBookingStats(): Promise<BookingStats | null> {
  const { data, error } = await supabase
    .from('app_settings')
    .select('setting_value, updated_at')
    .eq('setting_key', 'booking_code_stats')
    .limit(1);

  if (error || !data || data.length === 0) return null;

  const row: any = data[0];
  let payload: any = row.setting_value;
  if (typeof payload === 'string') {
    try {
      payload = JSON.parse(payload);
    } catch {
      return null;
    }
  }
  if (!payload || typeof payload !== 'object') return null;

  return {
    attempts: payload.attempts ?? null,
    successes: payload.successes ?? null,
    failures: payload.failures ?? null,
    lastError: payload.last_error ?? null,
    lastErrorAt: payload.last_error_at ?? null,
    lastSuccessAt: payload.last_success_at ?? row.updated_at ?? null,
  };
}

/**
 * Latest active SportyBet accumulator generated by the backend.
 *
 * Codes are built server-side (the SportyBet API rejects browser origins), so
 * the app only ever reads and shares them.
 */
export async function fetchLatestBookingCode(): Promise<BookingCode | null> {
  // `prediction_codes` is locked down by RLS, so the generated code is
  // published as a single app_settings row that the app is allowed to read.
  const { data, error } = await supabase
    .from('app_settings')
    .select('setting_value, updated_at')
    .eq('setting_key', 'booking_code')
    .eq('is_active', true)
    .limit(1);

  if (error || !data || data.length === 0) return null;

  const row: any = data[0];
  let payload: any = row.setting_value;
  if (typeof payload === 'string') {
    try {
      payload = JSON.parse(payload);
    } catch {
      return null;
    }
  }
  if (!payload || !payload.code) return null;

  // Choke point: a code that doesn't look like a SportyBet share token makes
  // the whole row unusable (the modal then shows the honest "not generated"
  // state instead of echoing or linking whatever arrived).
  const code = sanitizeBookingCode(payload.code);
  if (!code) return null;

  return {
    code,
    bookmaker: payload.bookmaker ?? 'sportybet-ng',
    expiresAt: payload.expires_at ?? null,
    createdAt: payload.generated_at ?? row.updated_at ?? null,
    shareUrl: typeof payload.share_url === 'string' ? payload.share_url : null,
    selections: Array.isArray(payload.selections) ? payload.selections : [],
  };
}

export function getPredictionSelection(prediction: Prediction): 'home' | 'draw' | 'away' {
  const pred = (prediction.prediction || '').toLowerCase();
  if (pred.includes('home') || pred === 'h' || pred === '1') return 'home';
  if (pred.includes('draw') || pred === 'd' || pred === 'x') return 'draw';
  if (pred.includes('away') || pred === 'a' || pred === '2') return 'away';
  // Fallback based on team names in match_title
  if (prediction.match_title?.toLowerCase().startsWith(prediction.home_team?.toLowerCase())) {
    return 'home';
  }
  if (prediction.match_title?.toLowerCase().startsWith(prediction.away_team?.toLowerCase())) {
    return 'away';
  }
  return 'home';
}

export function formatSelectionLabel(prediction: Prediction): string {
  const sel = getPredictionSelection(prediction);
  if (sel === 'home') return prediction.home_team;
  if (sel === 'away') return prediction.away_team;
  return 'Draw';
}
